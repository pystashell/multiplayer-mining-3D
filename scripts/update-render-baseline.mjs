// Records the render fingerprints that tests/browser-render.test.js compares
// against. Run it only when a visual change is intended, and get that change
// through the manual UI review; a library upgrade must match the existing
// baseline instead of replacing it.
//
// `--public <dir>` captures from another copy of public/ — for example an
// export of the last release (`git archive <commit> public`) when a new scene
// is added during an upgrade, so its baseline still shows the shipped look.
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { launchBrowser } from '../tests/support/browser.js';
import { PUBLIC_ROOT, startStaticServer } from '../tests/support/static-server.js';
import { RENDER_BASELINE_PATH, RENDER_VIEWPORT, captureRenderScenes } from '../tests/support/render-scenes.js';

// Writes each fingerprint's blocks one grid row per line so a diff shows where
// on the board a change landed.
function formatBaseline(baseline) {
  const rowsByScene = new Map();
  for (const [name, fingerprint] of Object.entries(baseline.scenes)) {
    const rows = [];
    for (let row = 0; row < fingerprint.rows; row += 1) {
      const blocks = fingerprint.blocks.slice(row * fingerprint.columns, (row + 1) * fingerprint.columns);
      rows.push(blocks.map((block) => JSON.stringify(block)).join(', '));
    }
    rowsByScene.set(name, rows);
  }
  const placeholder = (name) => `@@blocks:${name}@@`;
  const skeleton = {
    ...baseline,
    scenes: Object.fromEntries(Object.entries(baseline.scenes).map(([name, fingerprint]) => [
      name,
      { ...fingerprint, blocks: placeholder(name) },
    ])),
  };
  let text = JSON.stringify(skeleton, null, 2);
  for (const [name, rows] of rowsByScene) {
    text = text.replace(
      JSON.stringify(placeholder(name)),
      `[\n${rows.map((row) => `        ${row}`).join(',\n')}\n      ]`,
    );
  }
  return `${text}\n`;
}

const publicFlag = process.argv.indexOf('--public');
const root = publicFlag >= 0 ? resolve(process.argv[publicFlag + 1]) : PUBLIC_ROOT;
const server = await startStaticServer({ root });
const browser = await launchBrowser();
try {
  const { fingerprints, problems, threeRevision } = await captureRenderScenes(browser, server.url);
  const issues = Object.values(problems).flat();
  if (issues.length > 0) throw new Error(`The page reported problems while capturing:\n${issues.join('\n')}`);
  const baseline = {
    note: 'Generated by npm run test:render-baseline. Update only for an intended, reviewed visual change.',
    capturedWith: {
      threeRevision,
      browser: browser.version.product,
      platform: process.platform,
    },
    viewport: RENDER_VIEWPORT,
    scenes: fingerprints,
  };
  await writeFile(RENDER_BASELINE_PATH, formatBaseline(baseline));
  console.log(`Recorded ${Object.keys(fingerprints).length} render fingerprints with Three.js r${threeRevision} in ${browser.version.product}.`);
} finally {
  await browser.close();
  await server.close();
}
